const SIDEBAR_COOKIE_NAME = "sidebar_state"
const SIDEBAR_COOKIE_MAX_AGE = 60 * 60 * 24 * 7
const SIDEBAR_WIDTH_MOBILE = "18rem"
const SIDEBAR_WIDTH_ICON = "3rem"
const SIDEBAR_KEYBOARD_SHORTCUT = "b"
// A press that travels less than this many pixels is a click, not a drag.
const SIDEBAR_DRAG_THRESHOLD = 3

type SidebarContextProps = {
  state: "expanded" | "collapsed"
  open: boolean
  setOpen: (open: boolean) => void
  openMobile: boolean
  setOpenMobile: (open: boolean) => void
  isMobile: boolean
  toggleSidebar: () => void
  /** Desktop width in rem, clamped to `SIDEBAR_WIDTH`. */
  width: number
  setWidth: (width: number) => void
  /** True while the rail is being dragged, so width transitions pause. */
  resizing: boolean
  setResizing: (resizing: boolean) => void
}

const SidebarContext = React.createContext<SidebarContextProps | null>(null)

function useSidebar() {
  const context = React.useContext(SidebarContext)
  if (!context) {
    throw new Error("useSidebar must be used within a SidebarProvider.")
  }

  return context
}

function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  className,
  style,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  defaultOpen?: boolean
  open?: boolean
  onOpenChange?: (open: boolean) => void
}) {
  const isMobile = useIsMobile()
  const [openMobile, setOpenMobile] = React.useState(false)

  // This is the internal state of the sidebar.
  // We use openProp and setOpenProp for control from outside the component.
  const [_open, _setOpen] = React.useState(defaultOpen)
  const open = openProp ?? _open
  const setOpen = React.useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const openState = typeof value === "function" ? value(open) : value
      if (setOpenProp) {
        setOpenProp(openState)
      } else {
        _setOpen(openState)
      }

      // This sets the cookie to keep the sidebar state.
      document.cookie = `${SIDEBAR_COOKIE_NAME}=${openState}; path=/; max-age=${SIDEBAR_COOKIE_MAX_AGE}`
    },
    [setOpenProp, open]
  )

  // Helper to toggle the sidebar.
  const toggleSidebar = React.useCallback(() => {
    return isMobile ? setOpenMobile((open) => !open) : setOpen((open) => !open)
  }, [isMobile, setOpen, setOpenMobile])

  // Adds a keyboard shortcut to toggle the sidebar.
  React.useEffect(() => {
    const handleKeyDown = (event: KeyboardEvent) => {
      if (
        event.key === SIDEBAR_KEYBOARD_SHORTCUT &&
        (event.metaKey || event.ctrlKey)
      ) {
        event.preventDefault()
        toggleSidebar()
      }
    }

    window.addEventListener("keydown", handleKeyDown)
    return () => window.removeEventListener("keydown", handleKeyDown)
  }, [toggleSidebar])

  // The user's chosen width, in rem. Clamped on the way in, so a stale or
  // edited localStorage value can't push the sidebar off the page.
  const [width, _setWidth] = React.useState(getStoredSidebarWidth)
  const setWidth = React.useCallback((value: number) => {
    _setWidth(clampSidebarWidth(value))
  }, [])
  const [resizing, setResizing] = React.useState(false)

  // We add a state so that we can do data-state="expanded" or "collapsed".
  // This makes it easier to style the sidebar with Tailwind classes.
  const state = open ? "expanded" : "collapsed"

  const contextValue = React.useMemo<SidebarContextProps>(
    () => ({
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
      width,
      setWidth,
      resizing,
      setResizing,
    }),
    [
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
      width,
      setWidth,
      resizing,
    ]
  )

  return (
    <SidebarContext.Provider value={contextValue}>
      <div
        data-slot="sidebar-wrapper"
        data-resizing={resizing || undefined}
        style={
          {
            "--sidebar-width": `${width}rem`,
            "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
            ...style,
          } as React.CSSProperties
        }
        className={cn(
          "group/sidebar-wrapper flex min-h-svh w-full has-data-[variant=inset]:bg-sidebar",
          // No text selection while the rail is dragged across the page.
          "data-resizing:select-none",
          className
        )}
        {...props}
      >
        {children}
      </div>
    </SidebarContext.Provider>
  )
}

function Sidebar({
  side = "left",
  variant = "sidebar",
  collapsible = "offcanvas",
  className,
  children,
  dir,
  ...props
}: React.ComponentProps<"div"> & {
  side?: "left" | "right"
  variant?: "sidebar" | "floating" | "inset"
  collapsible?: "offcanvas" | "icon" | "none"
}) {
  const { isMobile, state, openMobile, setOpenMobile, resizing } = useSidebar()

  if (collapsible === "none") {
    return (
      <div
        data-slot="sidebar"
        className={cn(
          "flex h-full w-(--sidebar-width) flex-col bg-sidebar text-sidebar-foreground",
          className
        )}
        {...props}
      >
        {children}
      </div>
    )
  }

  if (isMobile) {
    return (
      <Sheet open={openMobile} onOpenChange={setOpenMobile} {...props}>
        <SheetContent
          dir={dir}
          data-sidebar="sidebar"
          data-slot="sidebar"
          data-mobile="true"
          className="w-(--sidebar-width) bg-sidebar p-0 text-sidebar-foreground [&>button]:hidden"
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH_MOBILE,
            } as React.CSSProperties
          }
          side={side}
        >
          <SheetHeader className="sr-only">
            <SheetTitle>Sidebar</SheetTitle>
            <SheetDescription>Displays the mobile sidebar.</SheetDescription>
          </SheetHeader>
          <div className="flex h-full w-full flex-col">{children}</div>
        </SheetContent>
      </Sheet>
    )
  }

  return (
    <div
      className="group peer hidden text-sidebar-foreground md:block"
      data-state={state}
      data-collapsible={state === "collapsed" ? collapsible : ""}
      data-variant={variant}
      data-side={side}
      data-resizing={resizing || undefined}
      data-slot="sidebar"
    >
      {/* This is what handles the sidebar gap on desktop */}
      <div
        data-slot="sidebar-gap"
        className={cn(
          "relative w-(--sidebar-width) bg-transparent transition-[width] duration-200 ease-linear",
          // The width follows the pointer during a drag, with no easing.
          "group-data-resizing:transition-none",
          "group-data-[collapsible=offcanvas]:w-0",
          "group-data-[side=right]:rotate-180",
          variant === "floating" || variant === "inset"
            ? "group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4)))]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon)"
        )}
      />
      <div
        data-slot="sidebar-container"
        data-side={side}
        className={cn(
          "fixed inset-y-0 z-10 hidden h-svh w-(--sidebar-width) transition-[left,right,width] duration-200 ease-linear data-[side=left]:left-0 data-[side=left]:group-data-[collapsible=offcanvas]:left-[calc(var(--sidebar-width)*-1)] data-[side=right]:right-0 data-[side=right]:group-data-[collapsible=offcanvas]:right-[calc(var(--sidebar-width)*-1)] md:flex",
          "group-data-resizing:transition-none",
          // Adjust the padding for floating and inset variants.
          variant === "floating" || variant === "inset"
            ? "p-2 group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4))+2px)]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon) group-data-[side=left]:border-r group-data-[side=right]:border-l",
          className
        )}
        {...props}
      >
        <div
          data-sidebar="sidebar"
          data-slot="sidebar-inner"
          className="flex size-full flex-col bg-sidebar group-data-[variant=floating]:rounded-lg group-data-[variant=floating]:shadow-sm group-data-[variant=floating]:ring-1 group-data-[variant=floating]:ring-sidebar-border"
        >
          {children}
        </div>
      </div>
    </div>
  )
}

// Lucide's panel-left, plus the chevron from panel-left-close. Shifts are a
// percentage of the 24-wide viewBox, so they stay in the icon's own units
// when the font size scales. 0 leaves the divider at x=9 (sidebar open).
// -12.5% parks the divider at x=6 when the sidebar is shut, and the
// chevron follows so the turn doesn't leave it against the right edge.
// The chevron rotates on click only, over 500ms, slower than the divider's
// 200ms slide. Hover slides both together and leaves its direction alone.
function SidebarToggleIcon() {
  const { isMobile, open, openMobile } = useSidebar()
  const expanded = isMobile ? openMobile : open
  const glide =
    "transition-transform duration-200 ease-linear motion-reduce:transition-none"
  // The same shift for the divider and the chevron, so a hover moves them
  // as one. Closed, both rest 12.5% to the left.
  const shift = expanded
    ? "group-hover/button:-translate-x-[12.5%] group-focus-visible/button:-translate-x-[12.5%]"
    : "-translate-x-[12.5%] group-hover/button:translate-x-0 group-focus-visible/button:translate-x-0"

  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className="size-5"
    >
      <rect width="18" height="18" x="3" y="3" rx="2" />
      <path
        d="M9 4v16"
        className={cn(glide, "[transform-box:view-box]", shift)}
      />
      {/* Translation lives on the group, in viewBox units. Rotation stays
          on the path, around the chevron itself, and follows the open state. */}
      <g className={cn(glide, "[transform-box:view-box]", shift)}>
        <path
          d="m16 15-3-3 3-3"
          className={cn(
            "origin-center transition-transform duration-500 ease-linear [transform-box:fill-box] motion-reduce:transition-none",
            expanded ? "rotate-0" : "rotate-180"
          )}
        />
      </g>
    </svg>
  )
}

function SidebarTrigger({
  className,
  onClick,
  ...props
}: React.ComponentProps<typeof Button>) {
  const { toggleSidebar } = useSidebar()

  return (
    <Button
      data-sidebar="trigger"
      data-slot="sidebar-trigger"
      variant="ghost"
      size="icon-sm"
      className={cn(className)}
      onClick={(event) => {
        onClick?.(event)
        toggleSidebar()
      }}
      {...props}
    >
      <SidebarToggleIcon />
      <span className="sr-only">Toggle Sidebar</span>
    </Button>
  )
}

// The sidebar's right edge: drag it to resize, click it to toggle. It is the
// WAI-ARIA window-splitter pattern (a focusable `separator`), so the arrow
// keys resize it too, Home/End jump to the limits and Enter toggles. Width
// is in rem to keep pace with the font-size setting, and is saved once a
// drag or key press ends rather than on every pointer move.
function SidebarRail({
  className,
  onClick,
  onKeyDown,
  onPointerDown,
  onPointerMove,
  onPointerUp,
  onPointerCancel,
  ...props
}: React.ComponentProps<"div">) {
  const {
    isMobile,
    state,
    toggleSidebar,
    width,
    setWidth,
    resizing,
    setResizing,
  } = useSidebar()
  const drag = React.useRef<{
    pointerId: number
    startX: number
    startWidth: number
    width: number
    direction: 1 | -1
    moved: boolean
  } | null>(null)
  // Set when a drag just ended, so the click that follows it doesn't toggle.
  const skipClick = React.useRef(false)

  const commit = (value: number) => {
    const next = clampSidebarWidth(value)
    setWidth(next)
    saveSidebarWidth(next)
  }

  const endDrag = (event: React.PointerEvent<HTMLDivElement>) => {
    const current = drag.current
    if (!current || current.pointerId !== event.pointerId) return
    drag.current = null
    setResizing(false)
    if (event.currentTarget.hasPointerCapture(event.pointerId)) {
      event.currentTarget.releasePointerCapture(event.pointerId)
    }
    if (current.moved) {
      skipClick.current = true
      saveSidebarWidth(current.width)
    }
  }

  return (
    <div
      data-sidebar="rail"
      data-slot="sidebar-rail"
      role="separator"
      aria-orientation="vertical"
      aria-label="Resize sidebar"
      aria-valuemin={SIDEBAR_WIDTH.min}
      aria-valuemax={SIDEBAR_WIDTH.max}
      aria-valuenow={Math.round(width)}
      tabIndex={0}
      onClick={(event) => {
        onClick?.(event)
        if (event.defaultPrevented) return
        if (skipClick.current) {
          skipClick.current = false
          return
        }
        toggleSidebar()
      }}
      onKeyDown={(event) => {
        onKeyDown?.(event)
        if (event.defaultPrevented) return
        // The rail sits on the sidebar's trailing edge, so on the right-hand
        // variant the arrow that widens it points the other way.
        const side = event.currentTarget.closest("[data-side]")
        const grow = side?.getAttribute("data-side") === "right" ? -1 : 1
        switch (event.key) {
          case "ArrowRight":
            commit(width + grow * SIDEBAR_WIDTH.step)
            break
          case "ArrowLeft":
            commit(width - grow * SIDEBAR_WIDTH.step)
            break
          case "Home":
            commit(SIDEBAR_WIDTH.min)
            break
          case "End":
            commit(SIDEBAR_WIDTH.max)
            break
          case "Enter":
            toggleSidebar()
            break
          default:
            return
        }
        event.preventDefault()
      }}
      onPointerDown={(event) => {
        onPointerDown?.(event)
        if (event.defaultPrevented) return
        // A collapsed rail has no width to drag; its click still toggles.
        // The mobile sheet sets its own width, so there is nothing to drag.
        if (event.button !== 0 || state === "collapsed" || isMobile) return
        const side = event.currentTarget.closest("[data-side]")
        drag.current = {
          pointerId: event.pointerId,
          startX: event.clientX,
          startWidth: width,
          width,
          direction: side?.getAttribute("data-side") === "right" ? -1 : 1,
          moved: false,
        }
        event.currentTarget.setPointerCapture(event.pointerId)
      }}
      onPointerMove={(event) => {
        onPointerMove?.(event)
        const current = drag.current
        if (!current || current.pointerId !== event.pointerId) return
        const distance = event.clientX - current.startX
        if (!current.moved) {
          if (Math.abs(distance) < SIDEBAR_DRAG_THRESHOLD) return
          current.moved = true
          setResizing(true)
        }
        current.width = clampSidebarWidth(
          current.startWidth + current.direction * pxToRem(distance)
        )
        setWidth(current.width)
      }}
      onPointerUp={(event) => {
        onPointerUp?.(event)
        endDrag(event)
      }}
      onPointerCancel={(event) => {
        onPointerCancel?.(event)
        endDrag(event)
      }}
      className={cn(
        "absolute inset-y-0 z-20 hidden w-4 touch-none outline-hidden transition-all ease-linear group-data-[side=left]:-right-4 group-data-[side=right]:left-0 after:absolute after:inset-y-0 after:start-1/2 after:w-[2px] hover:after:bg-sidebar-border focus-visible:after:bg-ring sm:flex ltr:-translate-x-1/2 rtl:-translate-x-1/2",
        // The hairline stays lit for the whole drag, even once the pointer
        // outruns the rail.
        "data-resizing:after:bg-sidebar-border",
        "in-data-[side=left]:cursor-col-resize in-data-[side=right]:cursor-col-resize",
        "[[data-side=left][data-state=collapsed]_&]:cursor-e-resize [[data-side=right][data-state=collapsed]_&]:cursor-w-resize",
        "group-data-[collapsible=offcanvas]:translate-x-0 group-data-[collapsible=offcanvas]:after:left-full hover:group-data-[collapsible=offcanvas]:bg-sidebar",
        "[[data-side=left][data-collapsible=offcanvas]_&]:-right-2",
        "[[data-side=right][data-collapsible=offcanvas]_&]:-left-2",
        className
      )}
      data-resizing={resizing || undefined}
      {...props}
    />
  )
}

